import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
const root='D:/atlias-app';
const folder=fs.mkdtempSync('D:/atlias-test-runs/native-failure-');
let source=fs.readFileSync(path.join(root,'test/native-account-resume-check.mjs'),'utf8');
const anchor="await word('Resume session (1 of 40)');";
assert.ok(source.includes(anchor));
source=source.replace("const root = path.resolve(import.meta.dirname, '..');",'const root = '+JSON.stringify(root)+';');
source="process.on('message',m=>{if(m==='end-probe')process.exit(12)});\n"+source.replace(anchor,anchor+" throw Error('planted-native-cleanup-failure');");
const probe=path.join(folder,'probe.mjs'); fs.writeFileSync(probe,source);
let output='',timedOut=false;
const child=spawn(process.execPath,[probe],{cwd:root,windowsHide:true,env:{...process.env,ATLIAS_NATIVE_MANUAL:'0'},stdio:['ignore','pipe','pipe','ipc']});
child.stdout.on('data',data=>output+=data);child.stderr.on('data',data=>output+=data);
const timer=setTimeout(()=>{timedOut=true;child.send('end-probe');},15000);
const exit=await new Promise((resolve,reject)=>{child.once('error',reject);child.once('exit',code=>resolve(code));}); clearTimeout(timer);
fs.writeFileSync(path.join(folder,'output.log'),output);
const result={expectedExit:1,actualExit:exit,naturalExit:!timedOut,plantedFailureObserved:output.includes('planted-native-cleanup-failure'),folder};
fs.writeFileSync(path.join(folder,'result.json'),JSON.stringify(result,null,2));
assert.equal(result.actualExit,1);assert.equal(result.naturalExit,true,'a failed native assertion must not leave its parent worker hanging');assert.equal(result.plantedFailureObserved,true);
console.log(JSON.stringify({...result,passed:true}));
